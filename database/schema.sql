CREATE DATABASE IF NOT EXISTS mvc_lab02 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mvc_lab02;
CREATE TABLE products(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL,price DECIMAL(10,2) NOT NULL,quantity INT NOT NULL,image_name VARCHAR(255) NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE customers(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(120) NOT NULL,email VARCHAR(150) NOT NULL UNIQUE,phone VARCHAR(30) NULL);
